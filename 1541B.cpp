void solve() {
    ll n;
    cin>>n;
    ll ans=0;
    vector<pair<ll,ll>>v(n);
    for(ll i=0;i<n;i++){
        cin>>v[i].first;
        v[i].second=i+1;
    }
    sort(v.begin(), v.end());
    for(ll i=0;i<n;i++){
        for(ll j=i+1;j<n;j++){
            if(v[i].first*v[j].first>=2*n)break;
            if(v[i].first*v[j].first==v[i].second+v[j].second)ans++;
        }
    }
    cout<<ans<<"\n";
}

